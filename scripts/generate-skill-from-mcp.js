#!/usr/bin/env node
const fs = require('node:fs').promises
const path = require('node:path')
const fetch = globalThis.fetch || require('node-fetch')
const process = require('node:process')

const srcUrl = process.argv[2] || 'https://mcp.vuetifyjs.com/'
const outDir = path.join(__dirname, '..', 'skills', 'vuetify')

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true })
}

async function fetchJson(u) {
  const res = await fetch(u, { headers: { Accept: 'application/json' } })
  if (!res.ok)
    throw new Error(`Fetch failed: ${res.status} ${u}`)
  return await res.json()
}

async function writeFiles(u, json) {
  await ensureDir(path.join(outDir, 'references'))
  const outJson = path.join(outDir, 'references', 'mcp.json')
  await fs.writeFile(outJson, JSON.stringify({ source: u, fetchedAt: new Date().toISOString(), payload: json }, null, 2), 'utf8')

  const mdPath = path.join(outDir, 'references', 'mcp-integration.md')
  const md = [
    '---',
    'name: mcp-integration',
    'description: Guidance for using the Vuetify MCP as a canonical source instead of scraping.',
    '---',
    '',
    '# Vuetify MCP Integration',
    '',
    `Source: ${u}`,
    '',
    'This file contains the raw MCP payload fetched from the source and an explanation on how to use it in skill generation scripts.',
    '',
    '- The JSON payload is written to `references/mcp.json`.',
    '- Use the MCP JSON to populate `SKILL.md` or specific reference files instead of scraping HTML.',
    '',
    'Example fetch snippet (Node):',
    '```js',
    'const data = require(\'./references/mcp.json\');',
    'console.log(data.source, data.fetchedAt);',
    '```',
    '',
    '<!-- Generated by scripts/generate-skill-from-mcp.js -->',
  ].join('\n')
  await fs.writeFile(mdPath, md, 'utf8')

  const genPath = path.join(outDir, 'GENERATION.md')
  const gen = `# Generation Info\n\n- **Source:** ${u}\n- **Generated:** ${new Date().toISOString()}\n`
  await fs.writeFile(genPath, gen, 'utf8')
}

async function run() {
  console.log('Fetching MCP JSON from', srcUrl)
  // Attempt to fetch a sensible JSON endpoint, fallback to base URL
  const candidate = srcUrl.endsWith('/') ? `${srcUrl}design-context.json` : `${srcUrl}/design-context.json`
  let json
  try {
    json = await fetchJson(candidate)
  }
  catch {
    console.warn('Primary endpoint failed, trying base URL as JSON')
    json = await fetchJson(srcUrl)
  }
  await writeFiles(srcUrl, json)
  console.log('MCP fetch complete: written to', path.join(outDir, 'references'))
}

run().catch((err) => {
  console.error(err)
  process.exit(1)
})
